#include <iostream>
#include <vector>
using namespace std;

// =========================================================================
// الدالة الأولى: merge
// وظيفتها: دمج نصفي مصفوفة مرتبين مسبقاً في مصفوفة واحدة كبيرة مرتبة بالكامل
// =========================================================================
void merge(int arr[], int left, int mid, int right) {
    // 1. حساب أطوال النصفين
    int n1 = mid - left + 1; // طول النصف الأيسر (من البداية حتى المنتصف)
    int n2 = right - mid;     // طول النصف الأيمن (من بعد المنتصف حتى النهاية)

    // 2. إنشاء مصفوفتين مؤقتتين لحفظ البيانات
    vector<int> l(n1); // مصفوفة مؤقتة للنصف الأيسر
    vector<int> r(n2); // مصفوفة مؤقتة للنصف الأيمن

    // 3. نسخ عناصر النصف الأيسر من المصفوفة الأصلية
    for (int i = 0; i < n1; i++) {
        l[i] = arr[left + i];  // left + i ==? which mean : left == arr[0]  so 0 + i = arr[0]  which is the first element
    }

    // 4. نسخ عناصر النصف الأيمن من المصفوفة الأصلية
    for (int j = 0; j < n2; j++) {
        r[j] = arr[mid + 1 + j]; // mid + 1 + j ==? which mean : mid + 1 == arr[mid + 1]  so mid + 1 + j = arr[mid + 1]  which is the first element of the right half
    }

    // 5. تهيئة المؤشرات للمقارنة
    int i = 0;    // مؤشر يبدأ من أول المصفوفة اليسرى (l)
    int j = 0;    // مؤشر يبدأ من أول المصفوفة اليمنى (r)
    int k = left; // مؤشر يحدد مكان الكتابة في المصفوفة الأصلية (arr)

    // 6. مقارنة العناصر واختيار الأصغر لوضعه في المصفوفة الأصلية
    while (i < n1 && j < n2) {
        if (l[i] <= r[j]) {
            arr[k] = l[i]; // العنصر الأيسر أصغر أو يساوي، نضعه في الأصلية
            i++;           // نحرك مؤشر اليسار خطوة للأمام
        } else {
            arr[k] = r[j]; // العنصر الأيمن أصغر، نضعه في الأصلية
            j++;           // نحرك مؤشر اليمين خطوة للأمام
        }
        k++; // نتحرك للخانة التالية في المصفوفة الأصلية
    }

    // 7. نقل أي عناصر متبقية في النصف الأيسر (إن وجدت)
    while (i < n1) {
        arr[k] = l[i];
        i++;
        k++;
    }

    // 8. نقل أي عناصر متبقية في النصف الأيمن (إن وجدت)
    while (j < n2) {
        arr[k] = r[j];
        j++;
        k++;
    }
}

// =========================================================================
// الدالة الثانية: mergeSort
// وظيفتها: تقسيم المصفوفة بالتكرار (Recursion) حتى تصبح عناصر منفردة، ثم استدعاء merge
// =========================================================================
void mergeSort(int arr[], int left, int right) {
    // شرط التوقف: إذا كان حجم الجزء عنصراً واحداً أو أقل (left >= right)
    if (left >= right) {
        return;
    }

    // حساب نقطة المنتصف لتفادي مشكلة الـ Overflow
    int mid = left + (right - left) / 2;

    // تقسيم النصف الأيسر وترتيبه
    mergeSort(arr, left, mid);

    // تقسيم النصف الأيمن وترتيبه
    mergeSort(arr, mid + 1, right);

    // دمج النصفين المرتبين معاً (مع تمرير mid كمعامل رابع)
    merge(arr, left, mid, right);
}

// =========================================================================
// الدالة الرئيسية: main
// =========================================================================
int main() {
    int arr[] = {2, 4, 5, 7, 9, 1, 3, 6, 8, 10};
    int n = sizeof(arr) / sizeof(arr[0]);

    // استدعاء خوارزمية الترتيب من أول عنصر (0) إلى آخر عنصر (n - 1)
    mergeSort(arr, 0, n - 1);

    // طباعة النتيجة النهائية
    cout << "Sorted Array using Merge Sort: ";
    for (int i = 0; i < n; i++) {
        cout << arr[i] << " ";
    }
    cout << "\n";

    return 0;
}
